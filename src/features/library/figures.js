/**
 * SVG for one step of an exercise.
 * @param {string} fig Figure type.
 * @param {number} step 0..2
 */
export function stepFigure(fig, step) {
  const f = FIGS[fig] ?? FIGS.squat;
  const [hd, sh, el, ha, hip, kn, ft] = f.frames[step];
  const line = (/** @type {P[]} */ pts) => pts.map((p, i) => `${i ? 'L' : 'M'}${p[0]} ${p[1]}`).join(' ');
  const weight = f.props === 'bar' || fig === 'thrust' || fig === 'squat'
    ? `<circle cx="${fig === 'thrust' ? hip[0] : ha[0]}" cy="${fig === 'thrust' ? hip[1] - 9 : ha[1]}" r="${fig === 'squat' ? 0 : 8}" fill="none" stroke="#33424B" stroke-width="4"/>`
    : f.props === 'db' ? `<rect x="${ha[0] - 6}" y="${ha[1] - 3}" width="12" height="6" rx="2" fill="#33424B"/>` : '';
  return `<svg width="100%" height="104" viewBox="0 0 120 104" aria-hidden="true">${PROPS[f.props ?? ''] ?? ''}
<rect x="0" y="93" width="120" height="11" fill="#BFE0E0"/>
<path d="${line([sh, hip, kn, ft])}" stroke="#0B8F96" stroke-width="7" stroke-linecap="round" stroke-linejoin="round" fill="none"/>
<path d="${line([sh, el, ha])}" stroke="#2BB8BE" stroke-width="5.5" stroke-linecap="round" stroke-linejoin="round" fill="none"/>
<circle cx="${hd[0]}" cy="${hd[1]}" r="7" fill="#0B8F96"/>${weight}</svg>`;
}
